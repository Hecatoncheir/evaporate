import 'dart:async';
import 'dart:isolate';

/// Где выполнить тяжёлую работу с байтами: хеш, сжатие, zip.
///
/// По умолчанию — отдельный изолят. На главном такая работа ест кадры: sha256
/// у нас чистый Dart, а zip и gzip хоть и уходят в zlib, но зовутся из
/// того же изолята, что рисует окно. Снимок в гигабайт превращался в
/// окно, которое минуту не отвечает, — ровно тогда, когда человек нажал
/// «Снять» и смотрит, что будет.
///
/// Параметром, а не прямым `Isolate.run`: иначе тест не отличит, ушла ли
/// работа с главного изолята, — результат-то одинаковый.
typedef Offload = Future<R> Function<R>(FutureOr<R> Function() job);

Future<R> runInIsolate<R>(FutureOr<R> Function() job) => Isolate.run(job);

/// С какого размера файл стоит отдельного изолята.
///
/// Заведение изолята стоит несколько миллисекунд, а сейвы — это часто
/// тысячи мелких файлов, и изолят на каждый растянул бы снимок из секунды
/// в минуту. Файл меньше мегабайта стоит главному изоляту самое большее
/// кадра-другого, и платить за него изолятом — дороже.
const offloadFromBytes = 1 << 20;
