import '../../models/game.dart';

/// Одна ли это игра по названию.
///
/// Идентификаторы игр на разных устройствах не совпадают, и пакет с другой
/// машины узнаёт свою игру только по названию. Регистр и пробелы по краям
/// не в счёт: их расставляет человек, заводя игру, а не сама игра.
bool sameGameTitle(String a, String b) =>
    a.trim().toLowerCase() == b.trim().toLowerCase();

/// Игры библиотеки для выбора, куда лечь пакету: совпавшие по названию —
/// первыми, остальные в прежнем порядке.
///
/// Чаще всего игра уже есть под тем же названием, и искать её в длинном
/// списке незачем. Прочие не отбрасываются: название на другом устройстве
/// могли записать иначе.
List<Game> gamesMatchingFirst(List<Game> games, String title) => [
  ...games.where((g) => sameGameTitle(g.title, title)),
  ...games.where((g) => !sameGameTitle(g.title, title)),
];
