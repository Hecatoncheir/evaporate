import 'dart:async';

/// Один шаг завершения: дописать файл, погасить движок, снять значок.
typedef ShutdownStep = Future<void> Function();

/// Корректное завершение приложения.
///
/// Половина записей на диск отложена: библиотека ложится через 400 мс после
/// правки, положение окна — через 500. А закрытие окна и «Выход» в трее
/// обрывают процесс мгновенно, и до сих пор `close()` у блоков не вызывал
/// никто. Терялось при этом ровно то, что человек только что сделал:
/// наигранное время последнего сеанса, добавленная игра, подвинутое окно.
///
/// Шаги идут по очереди и независимо друг от друга: сбой одного не должен
/// стоить остальным их записи. Каждый ограничен по времени — зависший
/// движок не имеет права навсегда оставить окно на экране, потому что
/// пользователь уже нажал «Закрыть» и ждёт.
class AppShutdown {
  AppShutdown(
    this.steps, {
    this.stepTimeout = const Duration(seconds: 3),
    this.budget = const Duration(seconds: 8),
    this.onError,
  });

  final List<ShutdownStep> steps;

  /// Сколько ждать один шаг. Скорее страховка, чем норма: обычные шаги
  /// укладываются в миллисекунды.
  final Duration stepTimeout;

  /// Сколько всего ждать завершения.
  ///
  /// Одного предела на шаг мало: шагов полдесятка, и в худшем случае они
  /// складываются в полминуты неубираемого окна. Пользователь нажал
  /// «Закрыть» — окно обязано уйти, даже если движок повис.
  final Duration budget;

  /// Куда сообщить о сорвавшемся шаге. Показывать это уже некому — окно
  /// закрывается, — но в журнале отладки след остаться должен.
  final void Function(Object error)? onError;

  /// Идущий проход завершения.
  Future<void>? _running;

  /// Завершение уже запускали.
  bool get isStarted => _running != null;

  /// Проводит завершение — один раз.
  ///
  /// Закрытие окна и «Выход» в трее могут прийти одно за другим, и второй
  /// вызов получает **тот же** проход, а не пустой немедленный ответ: иначе
  /// второй `quit()` заканчивал процесс посреди первого прохода, так и не
  /// дописав его шаги.
  Future<void> run() => _running ??= _run();

  Future<void> _run() async {
    final deadline = Stopwatch()..start();
    for (final step in steps) {
      final left = budget - deadline.elapsed;
      if (left <= Duration.zero) {
        // Бюджет исчерпан. Оставшиеся шаги пропускаем молча: ждать дольше
        // мы уже пообещали не ждать, а окно всё ещё на экране.
        onError?.call(TimeoutException('Завершение не уложилось в $budget'));
        return;
      }
      try {
        await step().timeout(left < stepTimeout ? left : stepTimeout);
      } on Object catch (error) {
        // Ни сбой, ни зависание одного шага не отменяют остальные: у каждого
        // своя запись на диск, и терять их все из-за одного нельзя.
        onError?.call(error);
      }
    }
  }
}
