/// Дом приложения из командной строки: `--home=<папка>`.
///
/// Данные тогда лежат в `<папка>/data`, игры по умолчанию — в
/// `<папка>/games`, как у дымового запуска (`AppPaths.init(home:)`). Нужно,
/// чтобы запустить приложение на копии чужих данных — присланной
/// библиотеки, снимков, настроек, — не трогая своих. Замок экземпляра
/// лежит там же, поэтому такой запуск уживается с обычным.
///
/// Пустое значение — не дом: `--home=` без папки положило бы данные в
/// текущий каталог, куда никто их искать не станет.
String? launchHome(List<String> args) {
  const flag = '--home=';
  for (final arg in args) {
    if (arg.startsWith(flag) && arg.length > flag.length) {
      return arg.substring(flag.length);
    }
  }
  return null;
}
