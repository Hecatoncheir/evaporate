import 'package:flutter/widgets.dart';

/// Сколько точек расшифровывать картинке, показанной шириной [logical].
///
/// Без этого обложка разворачивается в полный размер файла: 600×900 —
/// около двух мегабайт, сорок восемь плиток — почти весь кэш картинок, а
/// выбранная человеком 2000×3000 — двадцать три мегабайта одна. Вверх
/// картинка не растягивается: ширина больше исходника ничего не прибавит.
///
/// Ступенями по 64 точки: протягивание окна иначе расшифровывало бы
/// обложку заново на каждую точку ширины.
int decodeWidth(BuildContext context, double logical) {
  final pixels = logical * MediaQuery.devicePixelRatioOf(context);
  if (!pixels.isFinite) return 1024;
  return ((pixels / 64).ceil() * 64).clamp(64, 4096);
}

