import 'package:flutter/widgets.dart';

/// Видно ли окно на экране — и только это решает, гнать ли кадры украшений.
///
/// `inactive` на рабочем столе означает «окно потеряло фокус», а не «окна не
/// видно»: человек щёлкнул по браузеру рядом, а наше окно осталось у него
/// перед глазами. Гасить по этому анимацию нельзя — со стороны замершие
/// искры и вставшая полоса загрузки выглядят зависшим приложением, причём
/// именно в тот момент, когда за загрузкой и следят из соседнего окна.
/// Батарею бережём на том, чего действительно не видно: свёрнутом
/// (`hidden`), усыплённом (`paused`) и отсоединённом (`detached`) окне.
bool isWindowVisible(AppLifecycleState? state) =>
    state == null ||
    state == AppLifecycleState.resumed ||
    state == AppLifecycleState.inactive;

/// Можно ли украшению двигаться прямо сейчас: окно видно, система не
/// просит не двигаться, раздел не погашен `TickerMode`, маршрут — текущий.
///
/// Одно правило на все украшения — и на часы (`DecorationClock`), и на
/// каплю выбора. Выписанное в каждом, оно однажды разошлось: фон
/// библиотеки при запуске не спрашивал, видно ли окно. Видимость читается
/// у привязки, а не хранится у виджета: к уведомлению о смене состояния
/// окна привязка его уже знает.
bool decorationMayRun(BuildContext context) =>
    isWindowVisible(WidgetsBinding.instance.lifecycleState) &&
    !MediaQuery.disableAnimationsOf(context) &&
    TickerMode.valuesOf(context).enabled &&
    (ModalRoute.isCurrentOf(context) ?? true);
