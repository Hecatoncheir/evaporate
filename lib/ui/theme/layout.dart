import 'package:flutter/widgets.dart';

import 'spacing.dart';

/// Размеры раскладки: поля страницы, предельная ширина, каркас оболочки.
///
/// Как и радиусы, они одни на обе схемы — разные поля в двух темах
/// читались бы как два разных приложения, — поэтому это постоянные, а не
/// поля расширения темы. Пока они стояли числами по месту, поле страницы
/// 28 было выписано в одиннадцати местах, а подпись настройки шириной 220 —
/// в одиннадцати других: сдвинь одно, и столбец настроек поедет лесенкой.
abstract final class EvaporateLayout {
  /// Поле страницы слева и справа: заголовки разделов, показания, сетка
  /// библиотеки и крупный кадр стоят по одной вертикали.
  static const gutter = 28.0;

  /// Отступ прокручиваемой страницы: поле по бокам и воздух сверху и снизу.
  static const pagePadding = EdgeInsets.fromLTRB(
    gutter,
    EvaporateSpacing.wide,
    gutter,
    EvaporateSpacing.vast,
  );

  /// Поле страницы по бокам и свой отступ сверху и снизу.
  static EdgeInsets inset({double top = 0, double bottom = 0}) =>
      EdgeInsets.fromLTRB(gutter, top, gutter, bottom);

  /// Предельная ширина содержимого. Дальше строка описания перестаёт
  /// читаться, карточка задачи превращается в полосу, а график скорости —
  /// в обои.
  static const contentMaxWidth = 1340.0;
  static const contentConstraints = BoxConstraints(maxWidth: contentMaxWidth);

  /// Отступ страницы из сливеров шириной [width]: то же, что [pagePadding]
  /// вокруг содержимого, зажатого [contentMaxWidth] и отцентрованного.
  ///
  /// Сливеры не коробки, в `Center` и `ConstrainedBox` их не обернуть:
  /// ширину и середину им задаёт боковой отступ.
  static EdgeInsets pagePaddingFor(double width) {
    final spare = width - 2 * gutter - contentMaxWidth;
    final side = gutter + (spare > 0 ? spare / 2 : 0);
    return EdgeInsets.fromLTRB(side, pagePadding.top, side, pagePadding.bottom);
  }

  /// Ширина подписи слева от органа настройки: органы всех карточек
  /// настроек встают в один столбец.
  static const settingLabelWidth = 220.0;

  /// Ширина диалога с формой, списком или раскладкой файлов: добавление
  /// игры, правило сохранений, восстановление, поиск игр, выбор
  /// исполняемого файла. Пока ширины стояли числами, у пяти диалогов их
  /// было три (520, 540, 560), и соседние окна одного приложения
  /// разнились на два десятка точек без всякой причины.
  static const dialogWidth = 560.0;

  /// Узкий диалог — выбор одного пункта из короткого списка: в широкой
  /// рамке строка висела бы посреди пустоты.
  static const dialogWidthNarrow = 460.0;

  /// Поле утопленной ниши: полки, поле поиска, знак в обойме. Это толщина
  /// стенки материала, а не отступ шкалы — поэтому три точки, а не
  /// ступень.
  static const wellInset = 3.0;

  /// Каркас окна: обойма разделов слева, рейка сверху и строка подсказок
  /// снизу. Числа — прототипа: обойма шириной в колонку клавиш с полем,
  /// рейка — в клавишу окна с воздухом, строка — в одну строку подсказок.
  static const railWidth = 76.0;
  static const topBarHeight = 58.0;
  static const hintsHeight = 32.0;

  /// Клавиша раздела в обойме и знак над ними: клавиша чуть ниже своей
  /// ширины, чтобы колонка читалась стопкой, а не лесенкой квадратов.
  static const railKey = Size(48, 44);
  static const railMark = 36.0;
}
