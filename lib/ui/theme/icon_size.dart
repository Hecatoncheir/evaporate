/// Размеры значков.
///
/// По месту стояло тринадцать чисел на девяносто с лишним значков, и 15,
/// 16 и 17 означали одно и то же — значок рядом с надписью или на
/// клавише: разница в точку читалась не как замысел, а как небрежность.
/// Ступеней шесть, и у каждой место, а не число.
///
/// Одни на обе схемы — значок не материал корпуса.
abstract final class EvaporateIconSize {
  /// Точка состояния: горит движок или нет.
  static const dot = 6.0;

  /// Отметка внутри показания: стрелка у скорости, палец у оценки.
  static const tiny = 12.0;

  /// Значок рядом с надписью: на клавише, в строке списка, у
  /// предупреждения.
  static const key = 16.0;

  /// Значок в заголовке, на панели инструментов и в меню.
  static const panel = 18.0;

  /// Значок-подсказка посреди пустой области: куда бросать, чего нет.
  static const large = 22.0;

  /// Значок-заставка: пустой раздел, ожидание нажатия кнопки.
  static const hero = 44.0;
}
