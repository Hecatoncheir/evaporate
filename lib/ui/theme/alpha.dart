/// Шкала прозрачностей для цвета, наложенного на корпус.
///
/// По месту стояли двадцать семь разных чисел на тридцать семь вызовов:
/// кант состояния был 0.34, 0.35 и 0.42, заливка под ним — 0.08, 0.09,
/// 0.13 и 0.14, и разница между ними ничего не значила, кроме того, что
/// писали в разное время. Ступеней шесть, и у каждой роль, а не число;
/// ещё три — прозрачность целого виджета (`Opacity`), а не цвета.
///
/// Альфы внутри художников (фольга, искры, пульс, график скорости) сюда не
/// входят: там прозрачность — часть расчёта анимации, а не ступень.
abstract final class EvaporateAlpha {
  /// Подкраска подложки строки под курсором: заметна, но не спорит с
  /// кантом, который берёт [strong].
  static const tint = 0.08;

  /// Заливка под цветом состояния и волосяная черта на стекле.
  static const subtle = 0.12;

  /// Тихий кант: разделитель строки состояния, рамка крупного кадра.
  static const soft = 0.25;

  /// Кант вокруг цветной плашки состояния.
  static const rim = 0.4;

  /// Кант при наведении — заметно сильнее покоя.
  static const strong = 0.55;

  /// Полоса поверх подложки: панель инструментов, строка состояния,
  /// заслонка под сбросом файла. Сквозь неё виден свет, но не детали.
  static const veil = 0.82;

  /// Карточка, поднятая перетаскиванием: чуть прозрачнее, чтобы под ней
  /// читалось, куда её несут.
  static const lifted = 0.9;

  /// Место, откуда карточку унесли: призрак, а не вторая карточка.
  static const ghost = 0.35;

  /// Подложка-показание под заголовком — график скорости под названием
  /// игры: виден, но текст над ним главнее.
  static const underlay = 0.5;
}
