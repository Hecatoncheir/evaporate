/// Шкала отступов: промежутки между элементами и поля внутри панелей.
///
/// По месту стояли двадцать девять разных чисел на двести с лишним мест:
/// 3, 5, 7, 9, 11 и 13 вперемешку с чётными, — и строка под названием
/// отходила от него на три точки в одном списке и на четыре в соседнем.
/// Шкала сняла с кода то, что в нём было на деле: ступени через две
/// точки до двадцати, дальше 24 и 32. Нечётное и промежуточное сведены к
/// ближайшей ступени, а страж темы ловит число в `SizedBox` и
/// `EdgeInsets` по месту.
///
/// Имя ступени — там, где она стоит чаще всего. Брать её можно и в другом
/// месте, если нужна та же величина: это шкала, а не словарь, и спор
/// «`gap` или `cluster`» решает то, сколько воздуха нужно, а не название.
///
/// Одни на обе схемы, как радиусы и раскладка: поля, разные в двух темах,
/// читались бы как два разных приложения. Размеры самих элементов —
/// ширина колонки, высота полосы — не отступы и живут в
/// `EvaporateLayout` или постоянной у своего виджета.
abstract final class EvaporateSpacing {
  /// Вплотную: подпись к своему значению, стрелка к числу показания.
  static const hair = 2.0;

  /// Строка к строке одной записи: название и строка показаний под ним,
  /// поле плашки сверху и снизу.
  static const line = 4.0;

  /// Плотный ряд: клавиши на полосе окна, пояснения одно под другим.
  static const tight = 6.0;

  /// Шаг по умолчанию: значок и надпись, соседние строки формы.
  static const gap = 8.0;

  /// Клавиши действий в ряд, органы одной группы.
  static const cluster = 10.0;

  /// Между полями формы и группами строк; поле строки списка.
  static const field = 12.0;

  /// От заголовка карточки до содержимого, между блоками карточки.
  static const block = 14.0;

  /// Поле панели, отступ под карточкой.
  static const panel = 16.0;

  /// Поле карточки раздела, просвет между колонками страницы.
  static const card = 18.0;

  /// Между частями страницы и диалога.
  static const section = 20.0;

  /// Воздух над страницей и вокруг крупных панелей.
  static const wide = 24.0;

  /// Крупная пустота: низ страницы, поля заставки.
  static const vast = 32.0;
}
