/// Каким приложение открывается при запуске.
///
/// Один выбор вместо набора галочек: «свёрнутым» и «развёрнутым» — не два
/// независимых признака, а взаимоисключающие варианты, и переключателями это
/// выражалось бы противоречиво.
enum WindowStartMode {
  /// Как оставили в прошлый раз: размер и положение восстанавливаются.
  remembered,

  /// Всегда во весь экран, что бы ни было запомнено.
  maximized,

  /// Свёрнутым в трей — окно не появляется.
  ///
  /// Ради этого варианта и нужен значок в трее: иначе запущенное приложение
  /// было бы ничем не открыть.
  minimized;

  static WindowStartMode fromName(String? name) => switch (name) {
    'maximized' => WindowStartMode.maximized,
    'minimized' => WindowStartMode.minimized,
    _ => WindowStartMode.remembered,
  };
}
