/// Украшение библиотеки: ключ в файле настроек и место в списке настроек.
///
/// Перечислимой, а не тринадцатью булевыми полями в `AppSettings`: каждое
/// поле выписывалось семь раз — конструктор, `copyWith`, `toJson`,
/// `fromJson`, `props` и оба набора, — и новое украшение означало десяток
/// правок, в которых легко перепутать флаг. Теперь оно значит строку
/// здесь, строку в наборе по умолчанию и подпись в настройках.
///
/// Порядок объявления — порядок переключателей в «Подробно», а `name` —
/// ключ виджета (`effects-<name>-toggle`), по которому их находят тесты:
/// переименование видно человеку и ломает тесты, случайно оно не пройдёт.
enum LibraryEffect {
  /// Частицы, всплывающие над сеткой. Заметнее прочего и на слабой машине
  /// стоят дороже всех — поэтому только по желанию.
  particles('particlesEnabled'),

  /// Волны света под полкой.
  waves('wavesEnabled'),

  /// Фольга: блик, идущий по обложке вслед за курсором.
  foil('foilEnabled'),

  /// Наклон карточки под курсором.
  cardTilt('cardTiltEnabled'),

  /// Жидкое искажение обложки.
  liquidDistortion('liquidDistortionEnabled'),

  /// Жидкая подложка под выбранным.
  liquidSelection('liquidSelectionEnabled'),

  /// Свет, которым выбранная игра заливает корпус оболочки.
  ambient('ambientEnabled'),

  /// Полоса света, раз в несколько секунд проходящая по крупной обложке.
  ///
  /// Единственное, что двигается по картинке само, — она и отличает живой
  /// кадр от вклеенной картинки. Своя настройка, потому что цена у неё
  /// своя: кадры идут всё время, пока библиотека открыта.
  heroSweep('heroSweepEnabled'),

  /// Кадры из игры подложкой под крупной обложкой: показываются по кругу и
  /// медленно ползут. Есть далеко не у всех игр — кадры приходят из Steam,
  /// а половина торрент-библиотеки с ним не сходится.
  shotsBackdrop('shotsBackdropEnabled'),

  /// Обложка приглушённым фоном на странице игры.
  coverBackdrop('coverBackdropEnabled'),

  /// Капли, стекающие по обложке выбранной игры.
  ///
  /// Единственный эффект на шейдере: рисует его видеокарта, и на слабой
  /// машине лучше знать об этом заранее, чем удивляться. Поэтому выключен.
  drops('dropsEnabled'),

  /// Искры, бегущие по краю обложки выбранной игры.
  portal('portalEnabled'),

  /// Рамка вокруг обложки, на которой стоит фокус.
  ///
  /// Выключена по умолчанию: место в сетке и без неё показывает рост
  /// обложки, а сама она спорит с рисунком. Общему выключателю украшений
  /// не подчиняется ([independent]) — рамка не украшение, а указатель
  /// места для того, кто ходит клавиатурой или геймпадом.
  selectionFrame('selectionFrameEnabled', independent: true),

  /// Проявления, переезды и всход полки.
  ///
  /// Включены по умолчанию: это не украшение сверху, а то, чем оболочка
  /// объясняет, что куда переехало. Системную просьбу не двигаться они
  /// слушают и без этой настройки.
  interfaceAnimations('interfaceAnimationsEnabled');

  const LibraryEffect(this.jsonKey, {this.independent = false});

  /// Ключ в файле настроек. Имена прежние: профили, записанные до этой
  /// правки, читаются как раньше.
  final String jsonKey;

  /// Не заперт общим выключателем украшений.
  final bool independent;

  /// С чем приложение поставляется.
  ///
  /// Список, а не флаг у каждого значения: он же служит набором «обычно»,
  /// и две записи одного и того же однажды разошлись бы. Выключенные по
  /// умолчанию просто не названы — их цена заметна глазу: частицы, капли
  /// на шейдере, жидкое искажение и рамка выбора.
  static const shipped = {
    waves,
    foil,
    cardTilt,
    ambient,
    heroSweep,
    shotsBackdrop,
    coverBackdrop,
    portal,
    interfaceAnimations,
  };

  /// Всё, что подчиняется общему выключателю.
  static Set<LibraryEffect> get decorative =>
      values.where((effect) => !effect.independent).toSet();
}
