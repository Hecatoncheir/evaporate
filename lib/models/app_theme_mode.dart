/// Какую схему показывать: свою или как в системе.
///
/// Своя перечислимая, а не `ThemeMode` из Flutter: настройки читают и
/// пишут там, где Flutter нет вовсе — в изоляте разбора базы путей и на
/// другом конце переноса. Имена совпадают с прежними значениями в файле
/// настроек, так что читается он как раньше.
enum AppThemeMode { system, light, dark }
