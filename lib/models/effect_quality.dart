/// Сколько украшения стоят кадру: эко, полное или наибольшее.
///
/// Не «что включено» — это набор украшений (`EffectPreset`), — а «насколько
/// дорого»: насколько густо, крупно и размыто. Качество — множитель, а не
/// подмножество флагов, поэтому в лестницу наборов оно не ложится и живёт
/// отдельным полем облика. Набор качество не трогает, и наоборот: «всё
/// включено, но экономно» — законный выбор для слабой машины.
enum EffectQuality {
  eco(factor: 0.5, blurScale: 0.55),
  full(factor: 1, blurScale: 1),
  max(factor: 1.6, blurScale: 1.15);

  const EffectQuality({required this.factor, required this.blurScale});

  /// Во сколько раз гуще или крупнее украшение против полного качества.
  final double factor;

  /// Во сколько раз сильнее размытие под стеклом. Растёт медленнее
  /// [factor]: с радиусом размытие дорожает быстрее, чем становится
  /// заметнее.
  final double blurScale;

  /// Незнакомое имя — полное качество: чужой или испорченный файл настроек
  /// не должен ни гасить украшения, ни разгонять их до наибольшего.
  static EffectQuality fromName(Object? name) => switch (name) {
    'eco' => EffectQuality.eco,
    'max' => EffectQuality.max,
    _ => EffectQuality.full,
  };
}
