/// Событие, которое приходит десятками в минуту и в журнал не идёт.
///
/// Журнал пишет имя каждого события (`LoggingBlocObserver`) — это и есть
/// «журнал причин», ради которого приложение держится Bloc. Но движок
/// загрузок сообщает о задачах каждую секунду, выбор в сетке меняется на
/// каждое нажатие стрелки, а поиск — на каждую букву: рассказ о случившемся
/// утонул бы в этой ленте. Такие события помечаются здесь, у себя, а не
/// списком в наблюдателе, — иначе наблюдатель знал бы все блоки поимённо.
abstract interface class FrequentEvent {}
