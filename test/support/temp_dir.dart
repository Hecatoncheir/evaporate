import 'dart:io';

/// Удаляет временную папку теста — с повтором там, где отказ означает
/// «ещё не отпустили», а не «не получится».
///
/// На Windows удалённый файл, который кто-то держит открытым, не исчезает,
/// а только помечается на удаление: исчезнет он, когда закроют последний
/// дескриптор. Держит его обычно не тест — все наши записи к уборке
/// дождаются, — а антивирус или индексатор, пришедший посмотреть на только
/// что записанный файл. Папка при этом уже пуста на вид, но система
/// считает её непустой (errno 145), а файл — занятым (errno 32); через
/// десяток миллисекунд то же удаление проходит. Так падал `tearDown` то в
/// одном файле, то в другом — после зелёных проверок.
///
/// Повторяем только эти два отказа и только на Windows: на остальных
/// системах удаление открытого файла проходит сразу, и отказ там — это
/// настоящая ошибка, которую прятать нельзя. Всё прочее бросается сразу, а
/// после последней попытки бросается и этот: висящий дольше секунды
/// дескриптор — уже не гонка, а утечка, и её надо видеть.
Future<void> deleteTempDir(Directory dir) async {
  const attempts = 10;
  for (var attempt = 1; ; attempt++) {
    try {
      if (await dir.exists()) await dir.delete(recursive: true);
      return;
    } on FileSystemException catch (error) {
      if (attempt == attempts || !_releasedSoon(error)) rethrow;
      // Нарастающая пауза: обычно хватает первой, а все вместе — меньше
      // секунды.
      await Future<void>.delayed(Duration(milliseconds: 20 * attempt));
    }
  }
}

/// errno 145 — «папка не пуста», 32 — «файл занят другим процессом».
bool _releasedSoon(FileSystemException error) =>
    Platform.isWindows && const {32, 145}.contains(error.osError?.errorCode);
